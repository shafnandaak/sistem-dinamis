  // Data Historis Laju Pertumbuhan Penduduk = WITH LOOKUP(Tahun Simulasi,([(2018,1.49)-(2025,1.06)],(2018,1.49),(2019,1.48),(2020,1.11),(2021,1.41),(2022,1.33),(2023,1.18),(2024,1.13),(2025,1.06)))
